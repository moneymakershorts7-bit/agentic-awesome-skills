"""Memory forensics analyzer helper functions.

Provides lazy logger initialization and common utility functions
for the memory forensics analyzer sub-modules.
"""
import threading

_lazy_init_lock = threading.Lock()

_logger = None


def _get_logger():
    """Lazy logger initialization to avoid importing logging at module load."""
    global _logger
    if _logger is None:
        with _lazy_init_lock:
            if _logger is None:
                import logging
                _logger = logging.getLogger("sec-userspace")
    return _logger
